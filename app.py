"""
app.py
======
Flask backend for SmartWater-AI (REAL Kaggle dataset:
region, date, consumption_liters).

Loads the trained model (best performer), feature-list artifacts, and recent
per-region history, then exposes:

    GET  /                -> main dashboard
    GET  /prediction      -> prediction interface
    GET  /forecast        -> 7-day forecast
    GET  /analytics       -> analytics section
    GET  /model-performance -> model performance metrics
    GET  /api/health       -> basic health check
    GET  /api/metrics      -> stored regression evaluation metrics
    GET  /api/classification-metrics -> stored classification evaluation metrics
    GET  /api/confusion-matrix       -> confusion matrix of the best classifier
    POST /api/predict      -> JSON prediction endpoint (region + date)
    GET  /api/dashboard-stats -> dashboard statistics
    GET  /api/analytics-data -> analytics data
    GET  /api/feature-importance -> feature importance from model
    GET  /api/forecast     -> 7-day forecast data
    GET  /api/signal-audit -> white-noise tests + achievable information ceiling

Run:
    python app.py
Then open http://127.0.0.1:5000/
"""

import os
import json
import traceback
import pandas as pd

from flask import Flask, request, jsonify, render_template

from src.predict import DemandPredictor

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.join(HERE, "models")
DATA_DIR = os.path.join(HERE, "data", "processed")
METRICS_PATH = os.path.join(MODELS_DIR, "metrics.json")
DATA_PATH = os.path.join(DATA_DIR, "water_demand_clean.csv")

app = Flask(__name__)

# Load model + artifacts once at startup (best model per training results)
predictor = DemandPredictor(model_name="random_forest_model.joblib")

with open(METRICS_PATH) as f:
    METRICS = json.load(f)

CLASSIFICATION_METRICS_PATH = os.path.join(MODELS_DIR, "classification_metrics.json")
if os.path.exists(CLASSIFICATION_METRICS_PATH):
    with open(CLASSIFICATION_METRICS_PATH) as f:
        CLASSIFICATION_METRICS = json.load(f)
else:
    CLASSIFICATION_METRICS = {}

# Signal audit: proves the dataset is white noise and quantifies the achievable
# ceiling. Generated by `python analysis/signal_audit.py`; the app only reads it.
SIGNAL_AUDIT_PATH = os.path.join(HERE, "analysis", "signal_audit.json")
if os.path.exists(SIGNAL_AUDIT_PATH):
    with open(SIGNAL_AUDIT_PATH) as f:
        SIGNAL_AUDIT = json.load(f)
else:
    SIGNAL_AUDIT = {}

# Load the full real dataset for analytics
df = pd.read_csv(DATA_PATH)
df['date'] = pd.to_datetime(df['date'])


