    """Confusion matrix + per-class metrics for the best classifier."""
    if not CLASSIFICATION_METRICS or "results" not in CLASSIFICATION_METRICS:
        return jsonify({"error": "Classification metrics not found. Run python train_classifier.py"}), 404
